_lang_index = None


def _detect():
    from . import config
    lang = config.get("language", "")
    if not lang:
        lang = os.environ.get("LC_ALL") or os.environ.get("LC_MESSAGES") or os.environ.get("LANG") or "pl"
    return 0 if lang.lower().startswith("pl") else 1


def lang_code():
    global _lang_index
    if _lang_index is None:
        _lang_index = _detect()
    return "pl" if _lang_index == 0 else "en"


def tr(key, *args):
    global _lang_index
    if _lang_index is None:
        _lang_index = _detect()
    pair = _STRINGS.get(key)
    if pair is None:
        s = key
    else:
        s = pair[_lang_index]
    if args:
        try:
            return s.format(*args)
        except Exception:
            return s
    return s


def plain(key, *args):
    """Tekst bez znaków '&' (akceleratorów) i bez części po tabulatorze."""
    s = tr(key, *args)
    s = s.split("\t")[0]
    return s.replace("&&", "\0").replace("&", "").replace("\0", "&")
